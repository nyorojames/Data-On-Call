"""Demo model training script for Data On-Call v2.

Trains, validates, and packages a clearly labeled DEMO model on synthetic data
(data/synthetic_dev.csv generated by scripts/make_synthetic.py, seed 42).

Strict requirements:
- Strictly refuses any dataset containing real player rows (source='real').
- Same features in same order, same Pipeline (StandardScaler + LogisticRegression),
  same decision cutoff 0.50 as spec.md section 10.
- Evaluates with leave-one-session-out CV and reports accuracy vs majority baseline
  as a synthetic recovery check (not real-world quality).
- Requires oof_accuracy >= 0.60 and > baseline as a pipeline sanity check.
- Exports model/model.onnx and model/config.json atomically.
- Records full demo disclosures and real-data evaluation gate failure in config.json.
"""

