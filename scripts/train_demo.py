def load_and_validate_synthetic_data(
    data_path: Path,
) -> tuple[np.ndarray, np.ndarray, list[str], list[dict[str, Any]]]:
    """Load and validate synthetic dataset. Strictly refuses any real player data."""
    if not data_path.is_file():
        sys.stderr.write(f"ERROR: Data file not found: {data_path}\n")
        sys.exit(1)

    rows: list[dict[str, Any]] = []
    with open(data_path, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != EXPECTED_COLUMNS:
            sys.stderr.write(
                f"ERROR: CSV columns mismatch.\nExpected: {EXPECTED_COLUMNS}\nFound:    {reader.fieldnames}\n"
            )
            sys.exit(1)
        for row in reader:
            rows.append(row)

    if not rows:
        sys.stderr.write(f"ERROR: Data file {data_path} is empty.\n")
        sys.exit(1)

    # STRICT GUARD: Refuse any file containing source=real rows
    real_rows = [r for r in rows if r.get("source") == "real"]
    if real_rows:
        sys.stderr.write(
            f"ERROR: scripts/train_demo.py is for synthetic demo training only and strictly refuses real-data files.\n"
            f"Found {len(real_rows)} row(s) with source='real' in {data_path}.\n"
        )
        sys.exit(1)

    non_synthetic = [r for r in rows if r.get("source") != "synthetic"]
    if non_synthetic:
        sys.stderr.write(
            f"ERROR: All rows in {data_path} must have source='synthetic'. Found invalid source: {non_synthetic[0].get('source')}\n"
        )
        sys.exit(1)

    # Validate session IDs and value ranges
    sessions_seen: dict[str, list[dict[str, Any]]] = {}
    for r in rows:
        sid = r["session_id"]
        if not HEX_SESSION_REGEX.match(sid):
            sys.stderr.write(
                f"ERROR: Invalid session_id format '{sid}'. Must be a 16-64 char lowercase hex string.\n"
            )
            sys.exit(1)

        try:
            scene_no = int(r["scene_no"])
            level = int(r["level"])
            goal = int(r["goal"])
            prev_hints = int(r["prev_hints_used"])
            prev_risky = int(r["prev_risky_count"])
            prev_timeouts = int(r["prev_timeout_count"])
            prev_dec_time = float(r["prev_decision_time_sec"])
            hint_curr = int(r["hint_used_this_scene"])
            dec_time = float(r["decision_time_sec"])
            chose_risky = int(r["chose_risky"])
        except ValueError as err:
            sys.stderr.write(f"ERROR: Non-numeric data found in row: {err}\n")
            sys.exit(1)

        if scene_no not in (1, 2, 3):
            sys.stderr.write(f"ERROR: Invalid scene_no {scene_no}.\n")
            sys.exit(1)
        if level not in (0, 1):
            sys.stderr.write(f"ERROR: Invalid level {level}.\n")
            sys.exit(1)
        if goal not in (0, 1, 2):
            sys.stderr.write(f"ERROR: Invalid goal {goal}.\n")
            sys.exit(1)
        if prev_hints < 0 or prev_hints > 3:
            sys.stderr.write(f"ERROR: Invalid prev_hints_used {prev_hints}.\n")
            sys.exit(1)
        if prev_risky < 0 or prev_risky > 3:
            sys.stderr.write(f"ERROR: Invalid prev_risky_count {prev_risky}.\n")
            sys.exit(1)
        if prev_timeouts < 0 or prev_timeouts > 3:
            sys.stderr.write(f"ERROR: Invalid prev_timeout_count {prev_timeouts}.\n")
            sys.exit(1)
        if prev_dec_time < 0.0:
            sys.stderr.write(f"ERROR: Invalid prev_decision_time_sec {prev_dec_time}.\n")
            sys.exit(1)
        if hint_curr not in (0, 1):
            sys.stderr.write(f"ERROR: Invalid hint_used_this_scene {hint_curr}.\n")
            sys.exit(1)
        if dec_time < 0.0:
            sys.stderr.write(f"ERROR: Invalid decision_time_sec {dec_time}.\n")
            sys.exit(1)
        if chose_risky not in (0, 1):
            sys.stderr.write(f"ERROR: Invalid chose_risky {chose_risky}.\n")
            sys.exit(1)

        if scene_no == 1:
            if (
                prev_hints != 0
                or prev_risky != 0
                or prev_timeouts != 0
                or prev_dec_time != 0.0
            ):
                sys.stderr.write(
                    f"ERROR: Scene 1 must have 0 for all previous accumulated metrics (session {sid}).\n"
                )
                sys.exit(1)

        sessions_seen.setdefault(sid, []).append(r)

    # Verify every session has exactly 3 consecutive scenes (1, 2, 3)
    for sid, s_rows in sessions_seen.items():
        if len(s_rows) != 3:
            sys.stderr.write(
                f"ERROR: Session {sid} has {len(s_rows)} rows (must have exactly 3).\n"
            )
            sys.exit(1)
        s_scenes = [int(r["scene_no"]) for r in s_rows]
        if s_scenes != [1, 2, 3]:
            sys.stderr.write(
                f"ERROR: Session {sid} scenes are {s_scenes}, expected [1, 2, 3].\n"
            )
            sys.exit(1)

    X_list: list[list[float]] = []
    y_list: list[int] = []
    session_ids: list[str] = []

    for r in rows:
        feature_vals = [float(r[col]) for col in FEATURES]
        X_list.append(feature_vals)
        y_list.append(int(r[TARGET_LABEL]))
        session_ids.append(r["session_id"])

    X = np.array(X_list, dtype=np.float32)
    y = np.array(y_list, dtype=int)

    count_0 = int(np.sum(y == 0))
    count_1 = int(np.sum(y == 1))
    if count_0 == 0 or count_1 == 0:
        sys.stderr.write(
            f"ERROR: Target class '{TARGET_LABEL}' has only one class present (0s: {count_0}, 1s: {count_1}).\n"
        )
        sys.exit(1)
    if count_0 < 5 or count_1 < 5:
        sys.stderr.write(
            f"ERROR: Insufficient class representation: class 0 has {count_0} rows, "
            f"class 1 has {count_1} rows. Both classes must have at least 5 rows.\n"
        )
        sys.exit(1)

    return X, y, session_ids, rows


def train_demo(
    data_path: Path,
    out_dir: Path,
) -> None:
    print("=== Training Data On-Call v2 DEMO Model (Synthetic Pipeline) ===")
    print(f"Data source: {data_path}")

    X, y, session_ids, rows = load_and_validate_synthetic_data(data_path)
    groups = np.array(session_ids)
    num_sessions = len(set(session_ids))
    print(f"Loaded {len(y)} rows ({num_sessions} distinct sessions).")
    print("Cross-validation method: leave-one-session-out")

    # Evaluate recovery check via LOGO CV
    oof_accuracy, baseline_accuracy, gate_passed = evaluate_gate(
        X=X,
        y=y,
        groups=groups,
    )

    print("\n--- Synthetic Recovery Check (Pipeline Sanity Verification) ---")
    print(f"Out-of-fold Accuracy: {oof_accuracy:.4f}")
    print(f"Baseline Accuracy:    {baseline_accuracy:.4f}")
    print(f"Sanity Threshold:     {MIN_ACCURACY_THRESHOLD:.2f}")
    print(
        "NOTE: This check verifies that the training pipeline successfully recovers\n"
        "      the synthetic generator's rule. It does NOT demonstrate real-world\n"
        "      model quality or validity on human player behavior."
    )

    if not gate_passed:
        sys.stderr.write(
            f"\nSANITY CHECK FAILURE:\n"
            f"Synthetic recovery accuracy ({oof_accuracy:.4f}) failed to exceed threshold "
            f"({MIN_ACCURACY_THRESHOLD:.2f}) or majority baseline ({baseline_accuracy:.4f}).\n"
            f"Artifacts will not be written.\n"
        )
        sys.exit(1)

    print("\nSanity check PASSED. Fitting final pipeline and packaging demo artifacts...")

    # Fit final pipeline on all data
    final_pipeline = build_pipeline()
    final_pipeline.fit(X, y)

    out_dir.mkdir(parents=True, exist_ok=True)
    onnx_file = out_dir / "model.onnx"
    config_file = out_dir / "config.json"

    # Export ONNX and verify parity on all rows (< 1e-4)
    sha256 = export_and_verify_onnx(
        pipeline=final_pipeline,
        X=X,
        onnx_path=onnx_file,
    )

    config_data = {
        "features": FEATURES,
        "target": TARGET_LABEL,
        "model_type": "LogisticRegression",
        "cv_method": "leave-one-session-out",
        "num_sessions": num_sessions,
        "num_rows": len(y),
        "num_participants": None,
        "oof_accuracy": round(oof_accuracy, 4),
        "baseline_accuracy": round(baseline_accuracy, 4),
        "gate_threshold": MIN_ACCURACY_THRESHOLD,
        "decision_cutoff": DECISION_CUTOFF,
        "model_sha256": sha256,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "demo": True,
        "training_source": "synthetic",
        "synthetic_generator": {
            "script": "scripts/make_synthetic.py",
            "seed": 42,
            "rule": GENERATOR_RULE_DESCRIPTION,
        },
        "validated_on_real_data": False,
        "real_data_gate": REAL_DATA_GATE_RECORD,
        "version": "v2.0-demo",
    }

    config_temp = config_file.with_suffix(".tmp")
    with open(config_temp, mode="w", encoding="utf-8") as f:
        json.dump(config_data, f, indent=2)
    config_temp.replace(config_file)

    print(f"\nSuccessfully packaged DEMO model to {out_dir}")
    print(f"  Artifact: {onnx_file} (SHA256: {sha256[:16]}...)")
    print(f"  Config:   {config_file}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Train, evaluate, and package a clearly labeled DEMO model on synthetic data."
    )
    parser.add_argument(
        "--data",
        type=Path,
        default=Path("data") / "synthetic_dev.csv",
        help="Path to synthetic sessions CSV (default: data/synthetic_dev.csv).",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("model"),
        help="Output directory (default: model/).",
    )

    args = parser.parse_args()
    train_demo(data_path=args.data, out_dir=args.out_dir)


if __name__ == "__main__":
    main()
